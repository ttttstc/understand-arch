#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { inferArchDir } from "./project-paths.mjs";

function readJson(path, fallback) {
  if (!existsSync(path)) return fallback;
  return JSON.parse(readFileSync(path, "utf-8"));
}

function assertInsideArchDir(archDir, target) {
  const rel = relative(archDir, target);
  if (rel.startsWith("..") || rel === "" || /^[a-zA-Z]:/.test(rel)) {
    throw new Error(`Refusing to write outside ARCH_PROJECT_ROOT: ${target}`);
  }
}

function renderDoc(projectName, projectId, variant) {
  const title = variant === "claude" ? "Claude Code Project Context" : "Project Context for Agent Tools";
  return [
    `# ${title}`,
    "",
    "> Auto-generated by understand-arch v3.6. This file lives under `.understand-arch/` and is safe to regenerate.",
    "",
    "## Quick Reference",
    `- Project:${projectName}`,
    "- Architecture: see [../wiki/ARCHITECTURE.md](../wiki/ARCHITECTURE.md)",
    "- Project context: see [../wiki/00-project-context.md](../wiki/00-project-context.md)",
    "- API contracts: see [../wiki/03-interfaces.md](../wiki/03-interfaces.md)",
    "- DB schema: see [../wiki/04-data-models.md](../wiki/04-data-models.md)",
    "- External services: see [../wiki/13-pending-changes.md](../wiki/13-pending-changes.md)",
    "",
    "## How to enable",
    "",
    "To let Claude Code, Cursor, or another Agent tool auto-read this context, create a link or copy the file yourself:",
    "",
    "```bash",
    `ln -s .understand-arch/${projectId}/agent-context/CLAUDE.md ./CLAUDE.md`,
    "```",
    "",
    "understand-arch never writes, appends, formats, or overwrites files in your repository root.",
    "",
  ].join("\n");
}

export function initAgentContext(options = {}) {
  const archDir = inferArchDir(options);
  if (options.enabled === false || options.noAgentContext) return { archDir, skipped: true, files: [] };
  const layer = readJson(join(archDir, "specs", "arch-layer.json"), {});
  const projectName = layer.project?.name || basename(archDir);
  const projectId = basename(archDir);
  const outDir = join(archDir, "agent-context");
  mkdirSync(outDir, { recursive: true });
  const files = [
    { name: "AGENTS.md", variant: "agents" },
    { name: "CLAUDE.md", variant: "claude" },
  ];
  const written = [];
  for (const file of files) {
    const target = join(outDir, file.name);
    assertInsideArchDir(archDir, target);
    writeFileSync(target, renderDoc(projectName, projectId, file.variant), "utf-8");
    written.push(target);
  }
  return { archDir, outDir, files: written };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = Object.fromEntries(process.argv.slice(2).map((arg) => {
    const [key, ...rest] = arg.replace(/^--/, "").split("=");
    return [key, rest.length ? rest.join("=") : true];
  }));
  const result = initAgentContext({
    archDir: args["arch-dir"],
    projectRoot: args.workspace,
    projectId: args.project,
    noAgentContext: Boolean(args["no-agent-context"]),
  });
  console.log(JSON.stringify(result, null, 2));
}
